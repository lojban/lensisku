#!/usr/bin/env python3
"""Apply the hand-reviewed corrections in fixes_2026_10_29.py to dialogues.json.

Idempotent with respect to the *original* file: pass --src to start from a
pristine copy (default: dialogues.json itself, which is then rewritten).

  python3 scripts/apply_fixes.py [--src ORIG.json] [--out dialogues.json] [--log review/changes-2026-10-29.md]

Steps: legacy script-only entries -> structured lines/questions; global and
per-story SUBS on every Lojban string; per-line / per-question replacements;
fill/bank questions re-derived from their (changed) source line; doubtful
list rebuilt from D; `script` and `translation` re-rendered.
"""
import argparse, copy, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from dialogue_lib import parse_script_entry, render_script, render_translation, unblank, title_jbo  # noqa: E402
import fixes_2026_10_29 as F  # noqa: E402


def sub_all(s, subs):
    for pat, rep in subs:
        s = re.sub(pat, rep, s)
    return s


def locations(e):
    """Yield (where, text) for every Lojban string of a structured entry."""
    if title_jbo(e):
        yield "title", title_jbo(e)
    for n, ln in enumerate(e["lines"]):
        yield f"line {n}", ln["jbo"]
    for n, q in enumerate(e.get("questions", [])):
        if q["type"] in ("fill", "bank"):
            yield f"q {n}", unblank(q["jbo"])
            for k, c in enumerate(q.get("chips") or []):
                yield f"q {n} chip {k}", c
        else:
            yield f"q {n}", q["jbo"]
            for k, a in enumerate(q["answers"]):
                yield f"q {n} answer {k}", a["jbo"]


def bracket(line, answer):
    m = re.search(r"(?<![\w'.])" + re.escape(answer) + r"(?![\w'])", line)
    if not m:
        return None
    return line[: m.start()] + "[" + answer + "]" + line[m.end():]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(ROOT, "dialogues.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "dialogues.json"))
    ap.add_argument("--log", default=os.path.join(ROOT, "review", "changes-2026-10-29.md"))
    a = ap.parse_args()
    data = json.load(open(a.src, encoding="utf-8"))
    problems, log = [], ["# dialogues.json changes (review 2026-10-29)\n",
                         "Generated by scripts/apply_fixes.py from scripts/fixes_2026_10_29.py.\n",
                         "Names: a valid cmevla or a brivla after la (la + selbri) is kept as written; only names that are "
                         "neither are respelled (e.g. .bea. → .beas., .svetas. → .sfetas.).\n"]
    out = []
    for e0 in data:
        e = copy.deepcopy(e0)
        eid = e.get("id") or e.get("draft_id")
        fx = F.FIXES.get(eid, {})
        if "lines" not in e:  # legacy script-only entry
            lines, qs, spk = parse_script_entry(e)
            e["lines"], e["questions"] = lines, qs
            e.setdefault("speakers", spk)
            e.setdefault("doubtful", [])
        orig = dict(locations(e))
        if "lines" in fx:
            e["lines"] = [{"speaker": s, "jbo": j, "en": en} for s, j, en in fx["lines"]]
        if "questions" in fx:
            e["questions"] = copy.deepcopy(fx["questions"])
        if "speakers" in fx:
            e["speakers"] = fx["speakers"]
        if "title" in fx:
            e["title"] = dict(fx["title"])
        subs = F.SUBS + fx.get("SUBS", [])
        if isinstance(e.get("title"), dict):
            e["title"]["jbo"] = sub_all(e["title"]["jbo"], subs)
        for ln in e["lines"]:
            ln["jbo"] = sub_all(ln["jbo"], subs)
        for q in e.get("questions", []):
            q["jbo"] = sub_all(q["jbo"], subs)
            if "answer" in q:
                q["answer"] = sub_all(q["answer"], subs)
            if q.get("chips"):
                q["chips"] = [sub_all(c, subs) for c in q["chips"]]
            for an in q.get("answers", []):
                an["jbo"] = sub_all(an["jbo"], subs)
        changed_lines = set()
        for i, v in fx.get("L", {}).items():
            jbo, en = (v if isinstance(v, tuple) else (v, None))
            if i >= len(e["lines"]):
                problems.append(f"{eid}: L{i} out of range")
                continue
            e["lines"][i]["jbo"] = jbo
            if en is not None:
                e["lines"][i]["en"] = en
            changed_lines.add(i)
        qs = e.get("questions", [])
        for i, q in sorted(fx.get("Q", {}).items()):
            if i < len(qs):
                qs[i] = copy.deepcopy(q)
            else:
                qs.append(copy.deepcopy(q))
        e["questions"] = [q for q in qs if q is not None]
        for (qi, ai), jbo in fx.get("A", {}).items():
            e["questions"][qi]["answers"][ai]["jbo"] = jbo
        for n, q in enumerate(e["questions"]):
            if q["type"] in ("fill", "bank") and "line_index" in q:
                li = q["line_index"]
                ln = e["lines"][li]
                if not q["jbo"] or unblank(q["jbo"]) != ln["jbo"] or li in changed_lines:
                    nb = bracket(ln["jbo"], q["answer"])
                    if nb is None:
                        problems.append(f"{eid}: q{n} answer {q['answer']!r} not in line {li}: {ln['jbo']}")
                    else:
                        q["jbo"] = nb
                    q["en"] = ln.get("en", q.get("en"))
                    q["speaker"] = ln["speaker"]
        # doubtful
        for ln in e["lines"]:
            ln.pop("doubtful", None)
        cur = dict(locations(e))
        dl = []
        for where, cand, note in fx.get("D", []):
            if where not in cur:
                problems.append(f"{eid}: doubtful location {where!r} missing")
                continue
            dl.append({"where": where, "jbo": cur[where], "original": orig.get(where, ""), "candidate": cand, "note": note})
            if where.startswith("line "):
                e["lines"][int(where.split()[1])]["doubtful"] = note
        e["doubtful"] = dl
        ren = getattr(F, "SPEAKER_RENAMES", {})
        renamed = sorted({f"{sp['name']} → {ren[sp['name']]}" for sp in e.get("speakers", []) if sp["name"] in ren})
        for sp in e.get("speakers", []):
            sp["name"] = ren.get(sp["name"], sp["name"])
        for x in e["lines"] + e.get("questions", []):
            if x.get("speaker"):
                x["speaker"] = ren.get(x["speaker"], x["speaker"])
        e["script"] = render_script(e)
        e["translation"] = render_translation(e)
        out.append(e)
        # log
        diffs = [(w, orig.get(w, ""), t) for w, t in cur.items() if orig.get(w) != t]
        log.append(f"\n## {eid} — {e['title']['en'] if isinstance(e.get('title'), dict) else e.get('title')}\n")
        if not diffs:
            log.append("_no Lojban changes_\n")
        for w, o, t in diffs:
            log.append(f"- {w}: `{o}` → `{t}`" if o else f"- {w}: (new) `{t}`")
        for d in dl:
            log.append(f"- doubtful {d['where']}: {d['note']}")
        if renamed:
            log.append("- speaker labels (not a valid cmevla or brivla): " + ", ".join(renamed))
    json.dump(out, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(a.out, "a").write("\n")
    os.makedirs(os.path.dirname(a.log), exist_ok=True)
    open(a.log, "w", encoding="utf-8").write("\n".join(log) + "\n")
    for p in problems:
        print("PROBLEM:", p)
    print(f"wrote {a.out} ({len(out)} entries), log {a.log}")


if __name__ == "__main__":
    main()
