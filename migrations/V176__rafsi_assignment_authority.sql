    IF NOT FOUND THEN
        RETURN;
    END IF;

    UPDATE definitions
    SET
        cached_username = u_username,
        cached_langrealname = l_realname,
        cached_type_name = v_type_name,
        cached_valsiword = v_word,
        cached_rafsi = combined_rafsi(v_rafsi, d_rafsi),
