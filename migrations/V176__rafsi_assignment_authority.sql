            COALESCE(v_word, '') || ' ' ||
            COALESCE(combined_rafsi(v_rafsi, d_rafsi), '') || ' ' ||
            COALESCE(d_definition, '') || ' ' ||
            COALESCE(d_notes, '') || ' ' ||
            COALESCE(d_selmaho, '') || ' ' ||
            COALESCE(kw_text, '')
        )
    WHERE definitionid = p_definitionid;
END;
$$ LANGUAGE plpgsql;

