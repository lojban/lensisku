-- Preserve displaced nonbaseline tokens. Prefer the community definition whose
-- notes actually mention the token; otherwise use the earliest community entry.
-- If only officialdata definitions exist, retain the note-derived proposal on
-- that definition, never in the official word-level list.
WITH displaced AS (
    SELECT v.valsiid, token
    FROM valsi v
    LEFT JOIN official_rafsi_baseline b ON b.word = v.word
    CROSS JOIN LATERAL regexp_split_to_table(trim(v.rafsi), '\s+') token
    WHERE v.source_langid = 1 AND v.typeid IN (1, 2) AND token <> ''
      AND NOT (token = ANY(regexp_split_to_array(COALESCE(b.rafsi, ''), '\s+')))
), attributed AS (
    SELECT chosen.definitionid, string_agg(DISTINCT token, ' ' ORDER BY token) AS rafsi
    FROM displaced x
    CROSS JOIN LATERAL (
        SELECT d.definitionid FROM definitions d JOIN users u ON u.userid = d.userid
        WHERE d.valsiid = x.valsiid
        ORDER BY (u.username != 'officialdata') DESC,
                 (position(x.token in COALESCE(d.notes, '')) > 0) DESC, d.definitionid
        LIMIT 1
    ) chosen
    GROUP BY chosen.definitionid
)
UPDATE definitions d SET rafsi = concat_ws(' ', NULLIF(d.rafsi, ''), a.rafsi)
FROM attributed a WHERE d.definitionid = a.definitionid;

UPDATE valsi v SET rafsi = NULLIF(b.rafsi, '')
FROM official_rafsi_baseline b
WHERE v.word = b.word AND v.source_langid = 1 AND v.typeid IN (1, 2);
UPDATE valsi v SET rafsi = NULL
WHERE v.source_langid = 1 AND v.typeid IN (1, 2)
  AND NOT EXISTS (SELECT 1 FROM official_rafsi_baseline b WHERE b.word = v.word);

